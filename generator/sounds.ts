// The sounds half of `pnpm build:music` (docs/sounds/sounds.md): bundles every
// sound design into export/sounds/sounds.js, lists them in sounds.meta.json, and
// writes sounds.d.ts - the contract (sounds/types.ts, types only) plus the
// bundle's own exports - so the game reads the module typed.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSync } from "esbuild";
import { SOUNDS, SOUNDS_FORMAT, soundMeta } from "../sounds/index.ts";
import type { SoundsMetaFile } from "../sounds/types.ts";

export const SOUNDS_MODULE = "sounds.js";

/** The bundle's exports, declared after the contract's types. */
const BUNDLE_EXPORTS = `
/** The bundle's format: bumped when the contract changes incompatibly. */
export declare const SOUNDS_FORMAT: number;
/** Every sound design, in the order the site lists them. */
export declare const SOUNDS: readonly SoundDesign[];
export declare function soundById(id: string): SoundDesign | undefined;
export declare function soundMeta(s: SoundDesign): SoundMeta;
/** A design's values with every missing or out-of-range one replaced. */
export declare function resolveValues(params: readonly SoundParam[], values: SoundValues | undefined): SoundValues;
`;

/** sounds.d.ts: the contract, then the bundle's exports. */
export function soundsDeclarations(typesSource: string): string {
  return `// Generated by rail-island-music \`pnpm build:music\` (generator/sounds.ts). Do not edit.\n${typesSource}${BUNDLE_EXPORTS}`;
}

export function soundsMeta(): SoundsMetaFile {
  return {
    note: "Generated by rail-island-music `pnpm build:music`. Do not edit -- change the design in sounds/ and rebuild.",
    format: SOUNDS_FORMAT,
    module: SOUNDS_MODULE,
    sounds: SOUNDS.map(soundMeta),
  };
}

export function writeSounds(out: string): void {
  const dir = join(out, "sounds");
  mkdirSync(dir, { recursive: true });
  buildSync({
    entryPoints: ["sounds/index.ts"],
    bundle: true,
    format: "esm",
    target: "es2020",
    outfile: join(dir, SOUNDS_MODULE),
    legalComments: "none",
  });
  writeFileSync(join(dir, "sounds.meta.json"), JSON.stringify(soundsMeta(), null, 1) + "\n");
  writeFileSync(join(dir, "sounds.d.ts"), soundsDeclarations(readFileSync("sounds/types.ts", "utf8")));
  console.log(`${SOUNDS.length} sounds -> ${dir}/`);
}
